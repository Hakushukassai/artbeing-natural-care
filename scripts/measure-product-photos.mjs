import { readFile, writeFile } from "node:fs/promises";
import sharp from "sharp";

// Measure white margins without modifying or resampling the original photographs.
const sources = JSON.parse(await readFile("docs/official-product-images.json", "utf8"));
const entries = [];
for (const source of sources) {
  const { data, info } = await sharp(source.file)
    .removeAlpha()
    .toColourspace("srgb")
    .raw()
    .toBuffer({ resolveWithObject: true });
  const rows = new Uint32Array(info.height);
  const columns = new Uint32Array(info.width);
  for (let y = 0; y < info.height; y++)
    for (let x = 0; x < info.width; x++) {
      const index = (y * info.width + x) * info.channels;
      if (Math.min(data[index], data[index + 1], data[index + 2]) < 238) {
        rows[y]++;
        columns[x]++;
      }
    }
  const visibleRows = [...rows.keys()].filter((y) => rows[y] >= Math.max(3, info.width * 0.005));
  const visibleColumns = [...columns.keys()].filter(
    (x) => columns[x] >= Math.max(3, info.height * 0.005),
  );
  if (!visibleRows.length || !visibleColumns.length)
    throw new Error(`Empty product image: ${source.name}`);
  const left = Math.max(0, visibleColumns[0] - 3),
    top = Math.max(0, visibleRows[0] - 3);
  const right = Math.min(info.width, visibleColumns.at(-1) + 4),
    bottom = Math.min(info.height, visibleRows.at(-1) + 4);
  const frame = {
    left,
    top,
    width: right - left,
    height: bottom - top,
    imageWidth: info.width,
    imageHeight: info.height,
  };
  entries.push(`  [productImages[${JSON.stringify(source.name)}], ${JSON.stringify(frame)}],`);
  console.log(source.id, `${frame.width}x${frame.height} within ${info.width}x${info.height}`);
}
await writeFile(
  "src/data/product-photo-frames.ts",
  `import { productImages } from "./product-images";\n\nexport type ProductPhotoFrame = {left: number; top: number; width: number; height: number; imageWidth: number; imageHeight: number};\n\n// Generated by scripts/measure-product-photos.mjs. Original image bytes remain unchanged.\nexport const productPhotoFrames: Record<string, ProductPhotoFrame> = Object.fromEntries([\n${entries.join("\n")}\n]);\n`,
);
